/**
 * @file
 *
 * The voter's proof that its commitment holds a valid vote (validity.h), on
 * LaZer's linear proofs. The statement, A w + t = 0 over R_p of degree 1024
 * and p = MODP, with witness w = (r_0, ..., r_3, m, u):
 *
 *   sum_j B1_j r_j - c1 = 0
 *   sum_j b2_j r_j + m - c2 = 0
 *   m - u = 0
 *
 * with ||r|| <= B, m binary and ||u|| <= 1 (lazer/validity.py). A binary m
 * equal to a u of norm at most 1 has at most one coefficient 1, so m is X^j or
 * 0. Which j is a candidate is left to the tally.
 *
 * LaZer lifts the statement to its own ring of degree 64 and a 65-bit proof
 * modulus; the parameters, generated by its lin-codegen.sage, are in
 * lazer/validity.h.
 */

#include <stdlib.h>
#include <string.h>

#include "lazer.h"
#include "lazer/validity.h"
#include "validity.h"

#define N 		VALIDITY_DEG
#define P 		VALIDITY_P
#define W 		VALIDITY_WIDTH
#define ROWS 	3
#define COLS 	(W + 2)
#define PARAMS 	validity

/* floor(B^2) for the bound on ||r||, B = 1.2 sqrt(4 * 1024 * 2/3) as in
 * lazer/validity.py. */
#define L2_R 	3932

static const uint8_t ppseed[32] = "ctrsa21 vote validity, LaZer";

static int64_t centre(__int128 x) {
	x %= P;
	if (x > P / 2) {
		x -= P;
	} else if (x < -(P / 2)) {
		x += P;
	}
	return (int64_t) x;
}

/* The statement as LaZer reads it, A row-major with each polynomial's
 * coefficients in turn, then t, all centred mod p. */
typedef struct {
	int64_t *A, *t;
} stmt_t;

static int64_t *at(stmt_t *st, int row, int col) {
	return st->A + ((size_t) row * COLS + col) * N;
}

static void stmt_init(stmt_t *st, const int64_t *c1, const int64_t *c2,
		const int64_t *B1, const int64_t *b2) {
	st->A = calloc((size_t) ROWS * COLS * N, sizeof(int64_t));
	st->t = calloc((size_t) ROWS * N, sizeof(int64_t));
	for (int j = 0; j < W; j++) {
		memcpy(at(st, 0, j), B1 + (size_t) j * N, N * sizeof(int64_t));
		memcpy(at(st, 1, j), b2 + (size_t) j * N, N * sizeof(int64_t));
	}
	at(st, 1, W)[0] = 1;		/* + m */
	at(st, 2, W)[0] = 1;		/* m - u */
	at(st, 2, W + 1)[0] = -1;
	for (int i = 0; i < N; i++) {
		st->t[0 * N + i] = centre(-(__int128) c1[i]);
		st->t[1 * N + i] = centre(-(__int128) c2[i]);
	}
}

static void stmt_clear(stmt_t *st) {
	free(st->A);
	free(st->t);
}

/* Whether c = sum_j a[j] r[j] + m in Z_p[X]/(X^N + 1), r ternary. */
static int row_holds(const int64_t *c, const int64_t *a, const int64_t *r,
		const int64_t *m) {
	__int128 *acc = calloc(N, sizeof(__int128));
	int ok = 1;

	for (int j = 0; j < W; j++) {
		const int64_t *aj = a + (size_t) j * N, *rj = r + (size_t) j * N;

		for (int i = 0; i < N; i++) {
			if (rj[i] == 0) {
				continue;
			}
			for (int l = 0; l < N; l++) {
				__int128 x = (__int128) aj[l] * rj[i];
				if (i + l < N) {
					acc[i + l] += x;
				} else {
					acc[i + l - N] -= x;
				}
			}
		}
	}
	for (int i = 0; i < N && ok; i++) {
		ok = (acc[i] + (m != NULL ? m[i] : 0) - c[i]) % P == 0;
	}
	free(acc);
	return ok;
}

/* Whether (r, m) is a witness of the form the proof needs: r ternary with
 * ||r||^2 <= L2_R, m binary with at most one coefficient set. */
static int witness_ok(const int64_t *r, const int64_t *m) {
	int64_t l2 = 0, ones = 0;

	for (size_t i = 0; i < (size_t) W * N; i++) {
		if (r[i] < -1 || r[i] > 1) {
			return 0;
		}
		l2 += r[i] * r[i];
	}
	for (int i = 0; i < N; i++) {
		if (m[i] < 0 || m[i] > 1) {
			return 0;
		}
		ones += m[i];
	}
	return l2 <= L2_R && ones <= 1;
}

void validity_setup(void) {
	lazer_init();
}

size_t validity_proof_len(void) {
	return lin_params_get_prooflen(PARAMS);
}

int validity_prove(uint8_t *proof, size_t *len, const int64_t *c1,
		const int64_t *c2, const int64_t *B1, const int64_t *b2,
		const int64_t *r, const int64_t *m, const uint8_t *ctx, size_t ctxlen) {
	lin_prover_state_t Pr;
	polymat_t A;
	polyvec_t t, w;
	stmt_t st;
	int64_t *wv;
	INT_T(p, 1);

	/* LaZer's prover does not check its statement, and on a false one its
	 * responses leave the range the encoding is sized for and overrun the
	 * proof buffer. */
	if (!witness_ok(r, m) || !row_holds(c1, B1, r, NULL)
			|| !row_holds(c2, b2, r, m)) {
		return 0;
	}
	int_set_i64(p, P);
	POLYRING_T(Rp, p, N);
	stmt_init(&st, c1, c2, B1, b2);
	wv = malloc((size_t) COLS * N * sizeof(int64_t));
	memcpy(wv, r, (size_t) W * N * sizeof(int64_t));
	memcpy(wv + (size_t) W * N, m, N * sizeof(int64_t));
	memcpy(wv + (size_t) (W + 1) * N, m, N * sizeof(int64_t));	/* u = m */
	polymat_alloc(A, Rp, ROWS, COLS);
	polyvec_alloc(t, Rp, ROWS);
	polyvec_alloc(w, Rp, COLS);
	polymat_set_i64(A, st.A);
	polyvec_set_coeffvec_i64(t, st.t);
	polyvec_set_coeffvec_i64(w, wv);

	*len = validity_proof_len();
	lin_prover_init(Pr, ppseed, PARAMS);
	lin_prover_set_statement(Pr, A, t);
	lin_prover_set_witness(Pr, w);
	lin_prover_prove_ctx(Pr, proof, len, NULL, ctx, ctxlen);
	lin_prover_clear(Pr);

	polymat_free(A);
	polyvec_free(t);
	polyvec_free(w);
	free(wv);
	stmt_clear(&st);
	return 1;
}

int validity_verify(const uint8_t *proof, size_t len, const int64_t *c1,
		const int64_t *c2, const int64_t *B1, const int64_t *b2,
		const uint8_t *ctx, size_t ctxlen) {
	lin_verifier_state_t V;
	polymat_t A;
	polyvec_t t;
	stmt_t st;
	size_t used = len;
	int ok;
	INT_T(p, 1);

	/* The encoding's length varies; validity_proof_len() bounds it. */
	if (len == 0 || len > validity_proof_len()) {
		return 0;
	}
	int_set_i64(p, P);
	POLYRING_T(Rp, p, N);
	stmt_init(&st, c1, c2, B1, b2);
	polymat_alloc(A, Rp, ROWS, COLS);
	polyvec_alloc(t, Rp, ROWS);
	polymat_set_i64(A, st.A);
	polyvec_set_coeffvec_i64(t, st.t);

	lin_verifier_init(V, ppseed, PARAMS);
	lin_verifier_set_statement(V, A, t);
	ok = lin_verifier_verify_ctx(V, proof, &used, ctx, ctxlen) && used == len;
	lin_verifier_clear(V);

	polymat_free(A);
	polyvec_free(t);
	stmt_clear(&st);
	return ok;
}
