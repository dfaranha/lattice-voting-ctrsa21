/**
 * @file
 *
 * The voter's proof that its commitment holds a valid vote (validity.h), on
 * LaZer's linear proofs, stated over LaZer's own ring R_64 = Z_p[Y]/(Y^64 + 1),
 * p = MODP.
 *
 * R_p of degree N = 1024 is R_64[X]/(X^K - Y) with K = N / 64 = 16: an element
 * a is sum_k X^k a_k(Y), its piece a_k holding the coefficients a[k + K l]. A
 * vote for candidate j is X^(K j) = Y^j, which lives in piece 0 alone, so the
 * vote and the elements about it are single elements of R_64 rather than K of
 * them each, as lifting the statement from R_p would make them. With witness
 * w = (the K pieces of each of r_0, ..., r_3, m, m', u):
 *
 *   (sum_j B1_j r_j)_k - c1_k = 0				for k < K
 *   (sum_j b2_j r_j)_k + [k = 0] m - c2_k = 0	for k < K
 *   m - u = 0
 *   Y^(64 - ncand) m - m' = 0
 *
 * with ||r|| <= B, m and m' binary and ||u|| <= 1 (lazer/validity.py). The
 * first 2 K rows are the commitment equations in R_p, piece by piece, with the
 * vote's other pieces zero because they are not in the witness. A binary m
 * equal to a u of norm at most 1 is Y^j or 0. The last row makes j a
 * candidate: R_64 is negacyclic, so Y^(64 - ncand) Y^j is Y^(64 - ncand + j),
 * binary, for j < ncand, and -Y^(j - ncand), which is not, for j >= ncand. A
 * blank ballot, m = 0, is allowed.
 *
 * Lifting the statement from R_p made m and m' 16 binary elements of R_64
 * each; this way the binary part is 2 elements, not 32, and the witness 67,
 * not 112. The parameters, generated by LaZer's lin-codegen.sage, are in
 * lazer/validity.h.
 */

#include <stdlib.h>
#include <string.h>

#include "lazer.h"
#include "lazer/validity.h"
#include "validity.h"

#define N 		VALIDITY_DEG
#define P 		VALIDITY_P
#define W 		VALIDITY_WIDTH
#define D 		64					/* LaZer's ring degree */
#define K 		VALIDITY_STRIDE		/* N / D: pieces of an element of R_p */
#define ROWS 	(2 * K + 2)
#define COLS 	(W * K + 3)
#define COL_M 	(W * K)
#define COL_M2 	(W * K + 1)
#define COL_U 	(W * K + 2)
#define PARAMS 	validity

/* floor(B^2) for the bound on ||r||, B = 1.2 sqrt(4 * 1024 * 2/3) as in
 * lazer/validity.py. */
#define L2_R 	3932

static const uint8_t ppseed[32] = "ctrsa21 vote validity, LaZer";

static int64_t centre(__int128 x) {
	x %= P;
	if (x > P / 2) {
		x -= P;
	} else if (x < -(P / 2)) {
		x += P;
	}
	return (int64_t) x;
}

/* The statement as LaZer reads it, A row-major with each polynomial's
 * coefficients in turn, then t, all centred mod p. */
typedef struct {
	int64_t *A, *t;
} stmt_t;

static int64_t *at(stmt_t *st, int row, int col) {
	return st->A + ((size_t) row * COLS + col) * D;
}

/* Coefficient l of piece k of an element of R_p. */
#define PIECE(x, k, l) 	((x)[(k) + K * (l)])

/* Rows row0 .. row0 + K - 1: multiplication by x, from the K pieces of r_j in
 * columns j K .. j K + K - 1, as the K x K matrix whose entry (k, t) is
 * x_(k-t) for t <= k and Y x_(k-t+K) for t > k: X^(i+t) is X^k Y when i + t
 * wraps past K. */
static void mul_block(stmt_t *st, int row0, int j, const int64_t *x) {
	for (int k = 0; k < K; k++) {
		for (int t = 0; t < K; t++) {
			int64_t *e = at(st, row0 + k, j * K + t);

			if (t <= k) {
				for (int l = 0; l < D; l++) {
					e[l] = centre(PIECE(x, k - t, l));
				}
			} else {
				/* Y y: coefficient l is y's l - 1, and the top one wraps
				 * negated to the bottom */
				e[0] = centre(-(__int128) PIECE(x, k - t + K, D - 1));
				for (int l = 1; l < D; l++) {
					e[l] = centre(PIECE(x, k - t + K, l - 1));
				}
			}
		}
	}
}

static void stmt_init(stmt_t *st, const int64_t *c1, const int64_t *c2,
		const int64_t *B1, const int64_t *b2, int ncand) {
	st->A = calloc((size_t) ROWS * COLS * D, sizeof(int64_t));
	st->t = calloc((size_t) ROWS * D, sizeof(int64_t));
	for (int j = 0; j < W; j++) {
		mul_block(st, 0, j, B1 + (size_t) j * N);
		mul_block(st, K, j, b2 + (size_t) j * N);
	}
	at(st, K, COL_M)[0] = 1;				/* + m */
	at(st, 2 * K, COL_M)[0] = 1;			/* m - u */
	at(st, 2 * K, COL_U)[0] = -1;
	at(st, 2 * K + 1, COL_M)[D - ncand] = 1;	/* Y^(D - ncand) m - m' */
	at(st, 2 * K + 1, COL_M2)[0] = -1;
	for (int k = 0; k < K; k++) {
		for (int l = 0; l < D; l++) {
			st->t[(size_t) k * D + l] = centre(-(__int128) PIECE(c1, k, l));
			st->t[(size_t) (K + k) * D + l] = centre(-(__int128) PIECE(c2, k, l));
		}
	}
}

static void stmt_clear(stmt_t *st) {
	free(st->A);
	free(st->t);
}

/* Whether c = sum_j a[j] r[j] + m in Z_p[X]/(X^N + 1), r ternary. */
static int row_holds(const int64_t *c, const int64_t *a, const int64_t *r,
		const int64_t *m) {
	__int128 *acc = calloc(N, sizeof(__int128));
	int ok = 1;

	for (int j = 0; j < W; j++) {
		const int64_t *aj = a + (size_t) j * N, *rj = r + (size_t) j * N;

		for (int i = 0; i < N; i++) {
			if (rj[i] == 0) {
				continue;
			}
			for (int l = 0; l < N; l++) {
				__int128 x = (__int128) aj[l] * rj[i];
				if (i + l < N) {
					acc[i + l] += x;
				} else {
					acc[i + l - N] -= x;
				}
			}
		}
	}
	for (int i = 0; i < N && ok; i++) {
		ok = (acc[i] + (m != NULL ? m[i] : 0) - c[i]) % P == 0;
	}
	free(acc);
	return ok;
}

/* Whether (r, m) is a witness of the form the proof needs: r ternary with
 * ||r||^2 <= L2_R, m binary with at most one coefficient set, and that one
 * among the first ncand. */
static int witness_ok(const int64_t *r, const int64_t *m, int ncand) {
	int64_t l2 = 0, ones = 0;

	for (size_t i = 0; i < (size_t) W * N; i++) {
		if (r[i] < -1 || r[i] > 1) {
			return 0;
		}
		l2 += r[i] * r[i];
	}
	for (int i = 0; i < N; i++) {
		if (m[i] < 0 || m[i] > 1
				|| (m[i] != 0 && (i % K != 0 || i / K >= ncand))) {
			return 0;
		}
		ones += m[i];
	}
	return l2 <= L2_R && ones <= 1;
}

void validity_setup(void) {
	lazer_init();
}

size_t validity_proof_len(void) {
	return lin_params_get_prooflen(PARAMS);
}

int validity_prove(uint8_t *proof, size_t *len, const int64_t *c1,
		const int64_t *c2, const int64_t *B1, const int64_t *b2,
		const int64_t *r, const int64_t *m, int ncand, const uint8_t *ctx,
		size_t ctxlen) {
	lin_prover_state_t Pr;
	polymat_t A;
	polyvec_t t, w;
	stmt_t st;
	int64_t *wv;
	INT_T(p, 1);

	/* LaZer's prover does not check its statement, and on a false one its
	 * responses leave the range the encoding is sized for and overrun the
	 * proof buffer. */
	if (ncand < 1 || ncand > VALIDITY_MAXCAND || !witness_ok(r, m, ncand)
			|| !row_holds(c1, B1, r, NULL)
			|| !row_holds(c2, b2, r, m)) {
		return 0;
	}
	int_set_i64(p, P);
	POLYRING_T(Rp, p, D);
	stmt_init(&st, c1, c2, B1, b2, ncand);
	wv = calloc((size_t) COLS * D, sizeof(int64_t));
	for (int j = 0; j < W; j++) {
		for (int k = 0; k < K; k++) {
			for (int l = 0; l < D; l++) {
				wv[(size_t) (j * K + k) * D + l] = PIECE(r + (size_t) j * N, k, l);
			}
		}
	}
	for (int l = 0; l < D; l++) {
		wv[(size_t) COL_M * D + l] = PIECE(m, 0, l);
		wv[(size_t) COL_U * D + l] = PIECE(m, 0, l);	/* u = m */
	}
	for (int j = 0; j < ncand; j++) {				/* m' = Y^(D - ncand) m */
		wv[(size_t) COL_M2 * D + D - ncand + j] = PIECE(m, 0, j);
	}
	polymat_alloc(A, Rp, ROWS, COLS);
	polyvec_alloc(t, Rp, ROWS);
	polyvec_alloc(w, Rp, COLS);
	polymat_set_i64(A, st.A);
	polyvec_set_coeffvec_i64(t, st.t);
	polyvec_set_coeffvec_i64(w, wv);

	*len = validity_proof_len();
	lin_prover_init(Pr, ppseed, PARAMS);
	lin_prover_set_statement(Pr, A, t);
	lin_prover_set_witness(Pr, w);
	lin_prover_prove_ctx(Pr, proof, len, NULL, ctx, ctxlen);
	lin_prover_clear(Pr);

	polymat_free(A);
	polyvec_free(t);
	polyvec_free(w);
	free(wv);
	stmt_clear(&st);
	return 1;
}

int validity_verify(const uint8_t *proof, size_t len, const int64_t *c1,
		const int64_t *c2, const int64_t *B1, const int64_t *b2, int ncand,
		const uint8_t *ctx, size_t ctxlen) {
	lin_verifier_state_t V;
	polymat_t A;
	polyvec_t t;
	stmt_t st;
	size_t used = len;
	int ok;
	INT_T(p, 1);

	/* The encoding's length varies; validity_proof_len() bounds it. */
	if (len == 0 || len > validity_proof_len() || ncand < 1
			|| ncand > VALIDITY_MAXCAND) {
		return 0;
	}
	int_set_i64(p, P);
	POLYRING_T(Rp, p, D);
	stmt_init(&st, c1, c2, B1, b2, ncand);
	polymat_alloc(A, Rp, ROWS, COLS);
	polyvec_alloc(t, Rp, ROWS);
	polymat_set_i64(A, st.A);
	polyvec_set_coeffvec_i64(t, st.t);

	lin_verifier_init(V, ppseed, PARAMS);
	lin_verifier_set_statement(V, A, t);
	ok = lin_verifier_verify_ctx(V, proof, &used, ctx, ctxlen) && used == len;
	lin_verifier_clear(V);

	polymat_free(A);
	polyvec_free(t);
	stmt_clear(&st);
	return ok;
}
